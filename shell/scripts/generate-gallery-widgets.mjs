/**
 * Re-syncs the Gallery's example widgets from the widget-builder's own gallery
 * data (the A2UI spec's `catalogs/basic/examples/`, consolidated into
 * `src/data/gallery/v09/generated.ts` with per-widget masonry heights).
 *
 * The widget-builder lives in a sibling `private_a2ui_demo` clone (not part of
 * this repo). This copies its data verbatim, swapping the erasable
 * `import type { Widget }` for a self-contained local type block and renaming
 * the export. The generated file IS committed, so builds never depend on the
 * clone — only a re-sync does.
 *
 *   yarn generate:gallery-widgets            # default clone location
 *   node scripts/generate-gallery-widgets.mjs <path-to-generated.ts>
 */
import {readFileSync, writeFileSync, mkdirSync, existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join, resolve} from 'node:path';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const shellDir = join(scriptDir, '..');
const outFile = join(shellDir, 'src/app/gallery/gallery-widgets.generated.ts');

// a2ui-composer/composer-wt/ux-overhaul/shell/scripts -> a2ui-composer/
const defaultSource = resolve(
  scriptDir,
  '../../../../private_a2ui_demo/apps/widget-builder/src/data/gallery/v09/generated.ts',
);
const sourceFile = process.argv[2] ? resolve(process.argv[2]) : defaultSource;

if (!existsSync(sourceFile)) {
  console.error(
    `[generate-gallery-widgets] source not found:\n  ${sourceFile}\n` +
      `Pass the path to the widget-builder's data/gallery/v09/generated.ts as an argument, ` +
      `or clone private_a2ui_demo next to this repo. (The committed generated file is unchanged.)`,
  );
  process.exit(1);
}

const source = readFileSync(sourceFile, 'utf8');

// Take everything from the first widget block onward (drops the source file's
// AUTO-GENERATED banner, its `import type { Widget }`, and its GalleryEntry type).
const bodyStart = source.indexOf('\nconst ');
if (bodyStart === -1) {
  console.error('[generate-gallery-widgets] could not locate the first `const` widget block.');
  process.exit(1);
}
const body = source
  .slice(bodyStart + 1)
  .replace('export const V09_GALLERY_WIDGETS', 'export const GALLERY_WIDGETS');

const preamble = `/**
 * Copyright 2026 Google LLC
 *
 * Licensed under the Apache License, Version 2.0 (the "License");
 * you may not use this file except in compliance with the License.
 * You may obtain a copy of the License at
 *
 *     http://www.apache.org/licenses/LICENSE-2.0
 *
 * Unless required by applicable law or agreed to in writing, software
 * distributed under the License is distributed on an "AS IS" BASIS,
 * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
 * See the License for the specific language governing permissions and
 * limitations under the License.
 */

/* eslint-disable */
// GENERATED by scripts/generate-gallery-widgets.mjs — do not edit by hand.
// Source: private_a2ui_demo widget-builder src/data/gallery/v09/generated.ts
// (itself generated from the A2UI spec's catalogs/basic/examples/).
// Run \`yarn generate:gallery-widgets\` from shell/ to re-sync.

/** One named state of a widget's data model. */
export interface DataState {
  name: string;
  data: Record<string, unknown>;
}

/** A single A2UI component node in a widget tree. */
export interface A2UIComponent {
  id: string;
  [key: string]: unknown;
}

/** A composed example widget rendered in the Gallery masonry. */
export interface Widget {
  id: string;
  name: string;
  description?: string;
  createdAt: Date;
  updatedAt: Date;
  root: string;
  components: A2UIComponent[];
  dataStates?: DataState[];
}

/** A gallery entry: a widget plus its masonry cell height in pixels. */
export type GalleryEntry = { widget: Widget; height: number };

`;

mkdirSync(dirname(outFile), {recursive: true});
writeFileSync(outFile, `${preamble}${body}`, 'utf8');

const count = (body.match(/^const [A-Z_]+ = \{/gm) || []).length;
console.info(`[generate-gallery-widgets] wrote gallery-widgets.generated.ts — ${count} widgets.`);
